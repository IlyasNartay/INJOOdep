const storedLocale = typeof window !== "undefined" ? localStorage.getItem(STORAGE_KEY) : null;
export const locale = ref(storedLocale && messages[storedLocale] ? storedLocale : DEFAULT_LOCALE);

export const currentLanguage = computed(() => languageOptions.find((item) => item.value === locale.value) || languageOptions[0]);

export function setLocale(nextLocale) {
  if (!messages[nextLocale]) return;
  locale.value = nextLocale;
  if (typeof window !== "undefined") {
    localStorage.setItem(STORAGE_KEY, nextLocale);
    document.documentElement.lang = nextLocale;
  }
}

export function initializeLocale() {
  if (typeof window !== "undefined") {
    document.documentElement.lang = locale.value;
  }
}

export function t(path, fallback = "") {
  const parts = path.split(".");
  let result = messages[locale.value];

  for (const part of parts) {
    result = result?.[part];
    if (result == null) break;
  }

  return typeof result === "string" ? result : fallback || path;
}
